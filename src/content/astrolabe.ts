/** Each constellation's fork, centre outward; every link is listed once. */
function fork(
  c: 'silk' | 'choir' | 'aegis' | 'bond',
  rimA: string,
  rimB: string,
): [string, string][] {
  const a = `${c}_an`;
  const b = `${c}_bn`;
  return [
    ['star', `${c}_t1`],
    [`${c}_t1`, `${c}_t2`],
    [`${c}_t2`, `${c}_n1`],
    [`${c}_n1`, `${c}_a1`],
    [`${c}_a1`, `${c}_a2`],
    [`${c}_a2`, a],
    [a, `${c}_a3`],
    [`${c}_a3`, `${c}_a4`],
    [`${c}_a4`, rimA],
    [`${c}_n1`, `${c}_b1`],
    [`${c}_b1`, `${c}_b2`],
    [`${c}_b2`, b],
    [b, `${c}_b3`],
    [`${c}_b3`, `${c}_b4`],
    [`${c}_b4`, rimB],
  ];
}

