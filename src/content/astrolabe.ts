/**
 * The Astrolabe (docs/phase-4.md): a persistent passive tree of four constellations around the
 * Weaver's Star. Each is a fork: a trunk to its first notable, two branches to a second notable
 * and a keystone (Bond: a great notable) at the rim, and a bridge notable between neighbours.
 * Positions are map units, north up (precomputed: content uses no trigonometry). The sim knows
 * what each `effect` does (sim/mods.ts).
 */

type Node = ContentInput['astrolabe']['nodes'][number];

function travel(
  id: string,
  constellation: Node['constellation'],
  x: number,
  y: number,
  name: string,
  effect: string,
  values: Record<string, number>,
  text: string,
): Node {
  return { id, name, kind: 'travel', constellation, x, y, effect, values, text };
}

